#!/usr/bin/env python3
"""Builds server/nakama/modules/index.js for Nakama's JavaScript runtime.

Concatenates server/nakama/src/*.js (in file-name order) and embeds the game
data the server needs as WB_DATA, so the client and the server read the same
banners, characters, items and XP curve. Run after changing any of them:

    python3 tools/build_server_module.py
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "server/nakama/src"
OUT = ROOT / "server/nakama/modules/index.js"


def load(rel):
    return json.loads((ROOT / "data" / rel).read_text())


def as_list(d, key):
    v = d[key] if isinstance(d, dict) and key in d else d
    return list(v.values()) if isinstance(v, dict) else v


def xp_thresholds(curve):
    """Mirror of XpTable._build (scripts/skills/xp_table.gd)."""
    max_level = int(curve.get("max_level", 99))
    base = float(curve.get("base", 300.0))
    divisor = float(curve.get("divisor", 7.0))
    t = [0, 0]
    points = 0.0
    for lvl in range(1, max_level):
        points += math.floor(lvl + base * 2.0 ** (lvl / divisor))
        t.append(int(math.floor(points / 4.0)))
    return t[1:]  # index i -> xp to reach level i + 1


def main():
    rec = load("recruitment/banners.json")
    chars = as_list(load("characters/characters.json"), "characters")
    items = as_list(load("items/items.json"), "items")
    curves = load("skills/xp_curve.json")
    currencies = as_list(load("economy/currencies.json"), "currencies")
    world = load("regions/world_map.json")
    server = load("server/server_config.json")
    server["starting_wallet"] = {c["id"]: int(c.get("starting", 0)) for c in currencies}
    gacha_by_rarity = {}
    for c in chars:
        if c.get("acquisition") == "gacha":
            gacha_by_rarity.setdefault(c["rarity"], []).append(c["id"])
    data = {
        "version": "phase4-1",
        "rarity_order": rec["rarity_order"],
        "banners": rec["banners"],
        "character_rarity": {c["id"]: c["rarity"] for c in chars},
        "gacha_ids": {c["id"]: True for c in chars if c.get("acquisition") == "gacha"},
        "gacha_by_rarity": gacha_by_rarity,
        "items": {i["id"]: {"untradeable": bool(i.get("untradeable", False))} for i in items},
        "regions": [r["id"] for r in world["regions"]],
        "character_xp_table": xp_thresholds(curves.get("character_curve", {})),
        "server": server,
    }
    parts = ["// GENERATED by tools/build_server_module.py from server/nakama/src and data/. Do not edit.\n",
             "var WB_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n"]
    for f in sorted(SRC.glob("*.js")):
        parts.append(f"\n// ---- {f.name} ----\n" + f.read_text())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
